const DICTIONARIES: Record<Locale, Dictionary> = { fr, ar };

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

export function getT(locale: string): Translate {
  const dict = DICTIONARIES[(isLocale(locale) ? locale : DEFAULT_LOCALE) as Locale];
  const fallback = DICTIONARIES.fr;
  return (key, vars) => {
    let value = dict[key] ?? fallback[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        value = value.replaceAll(`{${k}}`, String(v));
      }
    }
    return value;
  };
}

export function dictionaryKeys(locale: Locale): string[] {
  return Object.keys(DICTIONARIES[locale]).sort();
}

export function localePath(locale: string, path: string): string {
  const clean = path === "/" ? "" : path.startsWith("/") ? path : `/${path}`;
  return `/${locale}${clean}`;
}

export function otherLocale(locale: string): Locale {
  return locale === "ar" ? "fr" : "ar";
}

